//! Stamp station model, catalogue loading and selection.
//!
//! The catalogue is generated from the operator's published GPX file (see
//! `data/official/` and `ATTRIBUTION.md`) and embedded into the binary so the
//! browser build needs no network access to list stamp stations. Nothing in
//! this crate performs I/O or knows about the user interface.

#![forbid(unsafe_code)]
#![deny(missing_docs)]

mod catalog;
mod error;
mod selection;
mod stamp;

pub use catalog::{CatalogDataset, StampCatalog};
pub use error::StampError;
pub use selection::StampSelection;
pub use stamp::{Stamp, StampId};

/// Highest station number supported by the model.
///
/// The Harzer Wandernadel numbers its stations sequentially; 999 leaves ample
/// headroom for growth while keeping the id a compact `u16`.
pub const MAX_STAMP_NUMBER: u16 = 999;

/// The catalogue embedded at compile time, generated by `cargo xtask data`.
pub const EMBEDDED_CATALOG_JSON: &str = include_str!(concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/../../data/catalog/hwn-2025-stamps.json"
));
